/**
 * Nusantara App Builder - Website WebView Starter Template
 * Secure, modern Android WebView with HTTPS default, offline caching,
 * Back-navigation dispatcher, external intent router, and error state view.
 */

import { CreateProjectInput, ProjectFile } from '../../../types/project';
import { COMPATIBLE_TOOLCHAIN } from './commonAndroidFiles';

export function generateWebViewStarterProject(input: CreateProjectInput): ProjectFile[] {
  const {
    name,
    displayName = name,
    packageId,
    minSdk = COMPATIBLE_TOOLCHAIN.minSdk,
    targetSdk = COMPATIBLE_TOOLCHAIN.targetSdk,
    compileSdk = COMPATIBLE_TOOLCHAIN.compileSdk,
    versionCode = 1,
    versionName = '1.0.0',
    description = '',
    targetUrl = 'https://nusantara.dev',
  } = input;

  const packagePath = packageId.replace(/\./g, '/');
  const themeName = `Theme.${name.replace(/[^a-zA-Z0-9]/g, '')}`;

  // app/build.gradle.kts
  const appBuildGradle = `plugins {
    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.android)
}

android {
    namespace = "${packageId}"
    compileSdk = ${compileSdk}

    defaultConfig {
        applicationId = "${packageId}"
        minSdk = ${minSdk}
        targetSdk = ${targetSdk}
        versionCode = ${versionCode}
        versionName = "${versionName}"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables {
            useSupportLibrary = true
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
        debug {
            applicationIdSuffix = ".debug"
            isDebuggable = true
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        viewBinding = true
    }
}

dependencies {
    implementation(libs.androidx.core.ktx)
    implementation(libs.androidx.appcompat)
    implementation(libs.material)
    implementation(libs.androidx.constraintlayout)
    implementation(libs.androidx.lifecycle.runtime.ktx)
    testImplementation(libs.junit)
    androidTestImplementation(libs.androidx.junit)
    androidTestImplementation(libs.androidx.espresso.core)
}
`;

  // AndroidManifest.xml with permissions
  const manifest = `<?xml version="1.0" encoding="utf-8"?>
<manifest xmlns:android="http://schemas.android.com/apk/res/android">

    <!-- Network permissions for WebView -->
    <uses-permission android:name="android.permission.INTERNET" />
    <uses-permission android:name="android.permission.ACCESS_NETWORK_STATE" />

    <application
        android:allowBackup="true"
        android:icon="@mipmap/ic_launcher"
        android:label="@string/app_name"
        android:roundIcon="@mipmap/ic_launcher_round"
        android:supportsRtl="true"
        android:theme="@style/${themeName}">
        <activity
            android:name=".MainActivity"
            android:configChanges="orientation|screenSize|keyboardHidden"
            android:exported="true">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity>
    </application>

</manifest>
`;

  // MainActivity.kt
  const mainActivity = `package ${packageId}

import android.annotation.SuppressLint
import android.content.Intent
import android.graphics.Bitmap
import android.net.Uri
import android.os.Bundle
import android.view.View
import android.webkit.WebChromeClient
import android.webkit.WebResourceError
import android.webkit.WebResourceRequest
import android.webkit.WebSettings
import android.webkit.WebView
import android.webkit.WebViewClient
import androidx.activity.OnBackPressedCallback
import androidx.appcompat.app.AppCompatActivity
import ${packageId}.databinding.ActivityMainBinding

/**
 * MainActivity - Generated by Nusantara App Builder (Phase 2)
 * Template: Website WebView Starter
 * Secure Android WebView wrapper with HTTPS default, back dispatcher, and network error handler.
 */
class MainActivity : AppCompatActivity() {

    private lateinit var binding: ActivityMainBinding
    private val initialTargetUrl = "${targetUrl}"

    @SuppressLint("SetJavaScriptEnabled")
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        binding = ActivityMainBinding.inflate(layoutInflater)
        setContentView(binding.root)

        setupWebView()
        setupBackNavigation()
        setupErrorHandling()

        binding.webView.loadUrl(initialTargetUrl)
    }

    @SuppressLint("SetJavaScriptEnabled")
    private fun setupWebView() {
        binding.webView.settings.apply {
            // Essential web settings
            javaScriptEnabled = true
            domStorageEnabled = true
            databaseEnabled = true
            useWideViewPort = true
            loadWithOverviewMode = true

            // Security best practices: Disallow local file access and enforce HTTPS
            allowFileAccess = false
            allowContentAccess = false
            mixedContentMode = WebSettings.MIXED_CONTENT_NEVER_ALLOW
            cacheMode = WebSettings.LOAD_DEFAULT
        }

        binding.webView.webChromeClient = object : WebChromeClient() {
            override fun onProgressChanged(view: WebView?, newProgress: Int) {
                if (newProgress < 100) {
                    binding.progressBar.visibility = View.VISIBLE
                    binding.progressBar.progress = newProgress
                } else {
                    binding.progressBar.visibility = View.GONE
                }
            }
        }

        binding.webView.webViewClient = object : WebViewClient() {
            override fun onPageStarted(view: WebView?, url: String?, favicon: Bitmap?) {
                binding.layoutError.visibility = View.GONE
                binding.progressBar.visibility = View.VISIBLE
            }

            override fun onPageFinished(view: WebView?, url: String?) {
                binding.progressBar.visibility = View.GONE
            }

            override fun onReceivedError(
                view: WebView?,
                request: WebResourceRequest?,
                error: WebResourceError?
            ) {
                // If main frame error, display friendly retry state
                if (request?.isForMainFrame == true) {
                    binding.progressBar.visibility = View.GONE
                    binding.layoutError.visibility = View.VISIBLE
                }
            }

            override fun shouldOverrideUrlLoading(view: WebView?, request: WebResourceRequest?): Boolean {
                val uri = request?.url ?: return false
                val scheme = uri.scheme?.lowercase() ?: ""

                // Handle external apps (e.g. tel:, mailto:, sms:, whatsapp:)
                if (scheme != "http" && scheme != "https") {
                    try {
                        val externalIntent = Intent(Intent.ACTION_VIEW, uri)
                        startActivity(externalIntent)
                        return true
                    } catch (e: Exception) {
                        return false
                    }
                }
                return false
            }
        }
    }

    private fun setupBackNavigation() {
        onBackPressedDispatcher.addCallback(this, object : OnBackPressedCallback(true) {
            override fun handleOnBackPressed() {
                if (binding.webView.canGoBack()) {
                    binding.webView.goBack()
                } else {
                    isEnabled = false
                    onBackPressedDispatcher.onBackPressed()
                }
            }
        })
    }

    private fun setupErrorHandling() {
        binding.btnRetry.setOnClickListener {
            binding.layoutError.visibility = View.GONE
            binding.webView.reload()
        }
    }

    override fun onDestroy() {
        binding.webView.destroy()
        super.onDestroy()
    }
}
`;

  // activity_main.xml
  const activityLayout = `<?xml version="1.0" encoding="utf-8"?>
<androidx.constraintlayout.widget.ConstraintLayout 
    xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:app="http://schemas.android.com/apk/res-auto"
    xmlns:tools="http://schemas.android.com/tools"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    tools:context=".MainActivity">

    <ProgressBar
        android:id="@+id/progressBar"
        style="?android:attr/progressBarStyleHorizontal"
        android:layout_width="match_parent"
        android:layout_height="4dp"
        android:max="100"
        android:indeterminate="false"
        android:progressDrawable="@drawable/ic_launcher_background"
        android:visibility="gone"
        app:layout_constraintTop_toTopOf="parent"
        app:layout_constraintStart_toStartOf="parent"
        app:layout_constraintEnd_toEndOf="parent" />

    <WebView
        android:id="@+id/webView"
        android:layout_width="0dp"
        android:layout_height="0dp"
        app:layout_constraintTop_toBottomOf="@id/progressBar"
        app:layout_constraintBottom_toBottomOf="parent"
        app:layout_constraintStart_toStartOf="parent"
        app:layout_constraintEnd_toEndOf="parent" />

    <!-- Network Error State Overlay -->
    <LinearLayout
        android:id="@+id/layoutError"
        android:layout_width="match_parent"
        android:layout_height="match_parent"
        android:orientation="vertical"
        android:gravity="center"
        android:padding="32dp"
        android:background="@color/background_light"
        android:visibility="gone"
        app:layout_constraintTop_toTopOf="parent"
        app:layout_constraintBottom_toBottomOf="parent"
        app:layout_constraintStart_toStartOf="parent"
        app:layout_constraintEnd_toEndOf="parent">

        <TextView
            android:layout_width="wrap_content"
            android:layout_height="wrap_content"
            android:text="Koneksi Bermasalah"
            android:textSize="20sp"
            android:textStyle="bold"
            android:textColor="@color/text_primary" />

        <TextView
            android:layout_width="wrap_content"
            android:layout_height="wrap_content"
            android:layout_marginTop="8dp"
            android:text="Gagal memuat halaman web. Pastikan perangkat Anda terhubung ke internet."
            android:textSize="14sp"
            android:gravity="center"
            android:textColor="@color/text_secondary" />

        <com.google.android.material.button.MaterialButton
            android:id="@+id/btnRetry"
            android:layout_width="wrap_content"
            android:layout_height="wrap_content"
            android:layout_marginTop="16dp"
            android:text="Coba Lagi" />

    </LinearLayout>

</androidx.constraintlayout.widget.ConstraintLayout>
`;

  // strings.xml
  const strings = `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <string name="app_name">${displayName}</string>
    <string name="target_url">${targetUrl}</string>
    <string name="description">${description || 'Aplikasi Android WebView Starter dibangun dengan Nusantara App Builder'}</string>
</resources>
`;

  return [
    { path: 'app/build.gradle.kts', name: 'build.gradle.kts', content: appBuildGradle, size: appBuildGradle.length },
    { path: 'app/src/main/AndroidManifest.xml', name: 'AndroidManifest.xml', content: manifest, size: manifest.length },
    { path: `app/src/main/java/${packagePath}/MainActivity.kt`, name: 'MainActivity.kt', content: mainActivity, size: mainActivity.length },
    { path: 'app/src/main/res/layout/activity_main.xml', name: 'activity_main.xml', content: activityLayout, size: activityLayout.length },
    { path: 'app/src/main/res/values/strings.xml', name: 'strings.xml', content: strings, size: strings.length },
  ];
}
