/**
 * Nusantara App Builder - Basic Activity Template (Material 3 & Architecture)
 */

import { CreateProjectInput, ProjectFile } from '../../../types/project';
import { COMPATIBLE_TOOLCHAIN } from './commonAndroidFiles';

export function generateBasicActivityProject(input: CreateProjectInput): ProjectFile[] {
  const {
    name,
    displayName = name,
    packageId,
    minSdk = COMPATIBLE_TOOLCHAIN.minSdk,
    targetSdk = COMPATIBLE_TOOLCHAIN.targetSdk,
    compileSdk = COMPATIBLE_TOOLCHAIN.compileSdk,
    versionCode = 1,
    versionName = '1.0.0',
    description = '',
  } = input;

  const packagePath = packageId.replace(/\./g, '/');
  const themeName = `Theme.${name.replace(/[^a-zA-Z0-9]/g, '')}`;

  // app/build.gradle.kts
  const appBuildGradle = `plugins {
    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.android)
}

android {
    namespace = "${packageId}"
    compileSdk = ${compileSdk}

    defaultConfig {
        applicationId = "${packageId}"
        minSdk = ${minSdk}
        targetSdk = ${targetSdk}
        versionCode = ${versionCode}
        versionName = "${versionName}"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables {
            useSupportLibrary = true
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
        debug {
            applicationIdSuffix = ".debug"
            isDebuggable = true
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        viewBinding = true
    }
}

dependencies {
    implementation(libs.androidx.core.ktx)
    implementation(libs.androidx.appcompat)
    implementation(libs.material)
    implementation(libs.androidx.constraintlayout)
    implementation(libs.androidx.lifecycle.runtime.ktx)
    implementation(libs.androidx.lifecycle.viewmodel.ktx)
    testImplementation(libs.junit)
    androidTestImplementation(libs.androidx.junit)
    androidTestImplementation(libs.androidx.espresso.core)
}
`;

  // AndroidManifest.xml
  const manifest = `<?xml version="1.0" encoding="utf-8"?>
<manifest xmlns:android="http://schemas.android.com/apk/res/android">

    <application
        android:allowBackup="true"
        android:icon="@mipmap/ic_launcher"
        android:label="@string/app_name"
        android:roundIcon="@mipmap/ic_launcher_round"
        android:supportsRtl="true"
        android:theme="@style/${themeName}">
        <activity
            android:name=".MainActivity"
            android:exported="true">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity>
    </application>

</manifest>
`;

  // MainActivity.kt with functional counter and click handlers
  const mainActivity = `package ${packageId}

import android.os.Bundle
import android.widget.Toast
import androidx.appcompat.app.AppCompatActivity
import ${packageId}.databinding.ActivityMainBinding

/**
 * MainActivity - Generated by Nusantara App Builder (Phase 2)
 * Template: Basic Activity (Material 3 UI, AppBar, and Interactive Actions)
 */
class MainActivity : AppCompatActivity() {

    private lateinit var binding: ActivityMainBinding
    private var clickCount = 0

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        binding = ActivityMainBinding.inflate(layoutInflater)
        setContentView(binding.root)

        setSupportActionBar(binding.toolbar)

        setupInteractions()
    }

    private fun setupInteractions() {
        // Floating action button listener
        binding.fabAction.setOnClickListener {
            clickCount++
            updateCounterUI()
            Toast.makeText(this, "Tombol ditekan! Hitungan: $clickCount", Toast.LENGTH_SHORT).show()
        }

        // Action button in content area
        binding.btnPrimaryAction.setOnClickListener {
            clickCount += 5
            updateCounterUI()
            Toast.makeText(this, "Aksi cepat +5! Total: $clickCount", Toast.LENGTH_SHORT).show()
        }

        // Reset button
        binding.btnReset.setOnClickListener {
            clickCount = 0
            updateCounterUI()
            Toast.makeText(this, "Hitungan direset ke 0", Toast.LENGTH_SHORT).show()
        }
    }

    private fun updateCounterUI() {
        binding.tvCounter.text = "Jumlah Aksi: $clickCount"
    }
}
`;

  // activity_main.xml
  const activityLayout = `<?xml version="1.0" encoding="utf-8"?>
<androidx.coordinatorlayout.widget.CoordinatorLayout 
    xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:app="http://schemas.android.com/apk/res-auto"
    xmlns:tools="http://schemas.android.com/tools"
    android:layout_width="match_parent"
    android:layout_height="match_parent"
    tools:context=".MainActivity">

    <com.google.android.material.appbar.AppBarLayout
        android:layout_width="match_parent"
        android:layout_height="wrap_content"
        android:theme="@style/ThemeOverlay.Material3.Dark.ActionBar">

        <com.google.android.material.appbar.MaterialToolbar
            android:id="@+id/toolbar"
            android:layout_width="match_parent"
            android:layout_height="?attr/actionBarSize"
            app:title="@string/app_name"
            app:titleTextColor="@android:color/white" />

    </com.google.android.material.appbar.AppBarLayout>

    <androidx.constraintlayout.widget.ConstraintLayout
        android:layout_width="match_parent"
        android:layout_height="match_parent"
        app:layout_behavior="@string/appbar_scrolling_view_behavior"
        android:padding="24dp">

        <TextView
            android:id="@+id/tvGreeting"
            android:layout_width="0dp"
            android:layout_height="wrap_content"
            android:text="@string/welcome_message"
            android:textSize="22sp"
            android:textStyle="bold"
            android:textColor="@color/text_primary"
            app:layout_constraintStart_toStartOf="parent"
            app:layout_constraintEnd_toEndOf="parent"
            app:layout_constraintTop_toTopOf="parent" />

        <TextView
            android:id="@+id/tvSubtitle"
            android:layout_width="0dp"
            android:layout_height="wrap_content"
            android:layout_marginTop="8dp"
            android:text="Dibangun dengan Material 3 di Nusantara App Builder"
            android:textSize="14sp"
            android:textColor="@color/text_secondary"
            app:layout_constraintStart_toStartOf="parent"
            app:layout_constraintEnd_toEndOf="parent"
            app:layout_constraintTop_toBottomOf="@id/tvGreeting" />

        <com.google.android.material.card.MaterialCardView
            android:id="@+id/cardCounter"
            android:layout_width="match_parent"
            android:layout_height="wrap_content"
            android:layout_marginTop="24dp"
            app:cardCornerRadius="12dp"
            app:cardElevation="2dp"
            app:layout_constraintTop_toBottomOf="@id/tvSubtitle">

            <LinearLayout
                android:layout_width="match_parent"
                android:layout_height="wrap_content"
                android:orientation="vertical"
                android:padding="16dp">

                <TextView
                    android:id="@+id/tvCounter"
                    android:layout_width="wrap_content"
                    android:layout_height="wrap_content"
                    android:text="Jumlah Aksi: 0"
                    android:textSize="18sp"
                    android:textStyle="bold"
                    android:textColor="@color/primary" />

                <LinearLayout
                    android:layout_width="match_parent"
                    android:layout_height="wrap_content"
                    android:orientation="horizontal"
                    android:layout_marginTop="12dp"
                    android:gravity="end">

                    <com.google.android.material.button.MaterialButton
                        android:id="@+id/btnReset"
                        style="@style/Widget.Material3.Button.TextButton"
                        android:layout_width="wrap_content"
                        android:layout_height="wrap_content"
                        android:text="Reset" />

                    <com.google.android.material.button.MaterialButton
                        android:id="@+id/btnPrimaryAction"
                        android:layout_width="wrap_content"
                        android:layout_height="wrap_content"
                        android:layout_marginStart="8dp"
                        android:text="Tambah +5" />

                </LinearLayout>

            </LinearLayout>

        </com.google.android.material.card.MaterialCardView>

    </androidx.constraintlayout.widget.ConstraintLayout>

    <com.google.android.material.floatingactionbutton.FloatingActionButton
        android:id="@+id/fabAction"
        android:layout_width="wrap_content"
        android:layout_height="wrap_content"
        android:layout_gravity="bottom|end"
        android:layout_margin="24dp"
        android:contentDescription="Action Button"
        app:srcCompat="@android:drawable/ic_input_add" />

</androidx.coordinatorlayout.widget.CoordinatorLayout>
`;

  // strings.xml
  const strings = `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <string name="app_name">${displayName}</string>
    <string name="welcome_message">Selamat Datang di ${displayName}</string>
    <string name="description">${description || 'Aplikasi Android Basic Activity dibangun dengan Nusantara App Builder'}</string>
</resources>
`;

  return [
    { path: 'app/build.gradle.kts', name: 'build.gradle.kts', content: appBuildGradle, size: appBuildGradle.length },
    { path: 'app/src/main/AndroidManifest.xml', name: 'AndroidManifest.xml', content: manifest, size: manifest.length },
    { path: `app/src/main/java/${packagePath}/MainActivity.kt`, name: 'MainActivity.kt', content: mainActivity, size: mainActivity.length },
    { path: 'app/src/main/res/layout/activity_main.xml', name: 'activity_main.xml', content: activityLayout, size: activityLayout.length },
    { path: 'app/src/main/res/values/strings.xml', name: 'strings.xml', content: strings, size: strings.length },
  ];
}
