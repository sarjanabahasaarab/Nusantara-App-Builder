/**
 * Nusantara App Builder - Android XML Layout Generator (Phase 3)
 * Converts visual design component models into production-standard Android XML Layouts and resource definitions.
 */

import {
  VisualComponent,
  VisualScreen,
  LayoutDimension,
  GeneratedLayoutResult,
} from '../../../types/visualDesigner';

/**
 * Escapes characters for Android XML attribute and text strings
 */
export function escapeXml(str: string): string {
  if (!str) return '';
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, "\\'");
}

/**
 * Formats dimension into Android dp string or keyword
 */
export function formatDimension(dim: LayoutDimension, defaultVal = 'wrap_content'): string {
  if (dim === 'match_parent' || dim === 'wrap_content') {
    return dim;
  }
  if (typeof dim === 'number') {
    return `${Math.max(0, Math.round(dim))}dp`;
  }
  return defaultVal;
}

/**
 * Converts VisualScreen into complete Android XML layout file
 */
export function generateAndroidXmlLayout(screen: VisualScreen): GeneratedLayoutResult {
  const extractedStrings: Record<string, string> = {};
  const extractedColors: Record<string, string> = {};

  const xmlBody = renderComponentToXml(screen.root, 0, true, extractedStrings, extractedColors);

  const fullXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by Nusantara App Builder (Visual Designer Engine Phase 3) -->
<!-- Screen: ${escapeXml(screen.name)} (ID: ${escapeXml(screen.id)}) -->
${xmlBody}
`;

  const fileName = screen.layoutFileName.endsWith('.xml')
    ? screen.layoutFileName
    : `${screen.layoutFileName}.xml`;

  return {
    fileName,
    relativePath: `app/src/main/res/layout/${fileName}`,
    fullXml,
    extractedStrings,
    extractedColors,
  };
}

/**
 * Recursive generator rendering a VisualComponent tree into formatted XML tags
 */
function renderComponentToXml(
  comp: VisualComponent,
  indentDepth: number,
  isRoot: boolean,
  stringsMap: Record<string, string>,
  colorsMap: Record<string, string>
): string {
  const indent = '    '.repeat(indentDepth);
  const childIndent = '    '.repeat(indentDepth + 1);
  const p = comp.properties;

  const width = formatDimension(p.width, isRoot ? 'match_parent' : 'wrap_content');
  const height = formatDimension(p.height, isRoot ? 'match_parent' : 'wrap_content');

  // Collect attribute list
  const attrs: string[] = [];

  // Namespaces on root tag
  if (isRoot) {
    attrs.push('xmlns:android="http://schemas.android.com/apk/res/android"');
    attrs.push('xmlns:app="http://schemas.android.com/apk/res-auto"');
    attrs.push('xmlns:tools="http://schemas.android.com/tools"');
  }

  // ID attribute
  attrs.push(`android:id="@+id/${escapeXml(comp.id)}"`);
  attrs.push(`android:layout_width="${width}"`);
  attrs.push(`android:layout_height="${height}"`);

  // Visibility
  if (p.visibility && p.visibility !== 'visible') {
    attrs.push(`android:visibility="${p.visibility}"`);
  }

  // Margins
  if (p.marginTop !== undefined && p.marginTop > 0) attrs.push(`android:layout_marginTop="${p.marginTop}dp"`);
  if (p.marginBottom !== undefined && p.marginBottom > 0) attrs.push(`android:layout_marginBottom="${p.marginBottom}dp"`);
  if (p.marginStart !== undefined && p.marginStart > 0) attrs.push(`android:layout_marginStart="${p.marginStart}dp"`);
  if (p.marginEnd !== undefined && p.marginEnd > 0) attrs.push(`android:layout_marginEnd="${p.marginEnd}dp"`);

  // Paddings
  if (p.paddingTop !== undefined && p.paddingTop > 0) attrs.push(`android:paddingTop="${p.paddingTop}dp"`);
  if (p.paddingBottom !== undefined && p.paddingBottom > 0) attrs.push(`android:paddingBottom="${p.paddingBottom}dp"`);
  if (p.paddingStart !== undefined && p.paddingStart > 0) attrs.push(`android:paddingStart="${p.paddingStart}dp"`);
  if (p.paddingEnd !== undefined && p.paddingEnd > 0) attrs.push(`android:paddingEnd="${p.paddingEnd}dp"`);

  // Background color
  if (p.backgroundColor) {
    attrs.push(`android:background="${escapeXml(p.backgroundColor)}"`);
  }

  // Alpha / Opacity
  if (p.opacity !== undefined && p.opacity < 1.0) {
    attrs.push(`android:alpha="${p.opacity.toFixed(2)}"`);
  }

  // Component-specific mapping
  switch (comp.type) {
    case 'linearLayout':
    case 'verticalLayout':
    case 'horizontalLayout': {
      const orientation =
        comp.type === 'horizontalLayout'
          ? 'horizontal'
          : p.orientation || (comp.type === 'verticalLayout' ? 'vertical' : 'vertical');

      attrs.push(`android:orientation="${orientation}"`);
      if (p.gravity) {
        attrs.push(`android:gravity="${p.gravity}"`);
      }

      const hasChildren = comp.children && comp.children.length > 0;
      if (!hasChildren) {
        return `${indent}<LinearLayout\n${attrs.map((a) => `${childIndent}${a}`).join('\n')} />`;
      }

      const renderedChildren = comp.children!
        .map((child) => renderComponentToXml(child, indentDepth + 1, false, stringsMap, colorsMap))
        .join('\n\n');

      return `${indent}<LinearLayout\n${attrs.map((a) => `${childIndent}${a}`).join('\n')}>\n\n${renderedChildren}\n\n${indent}</LinearLayout>`;
    }

    case 'card': {
      if (p.elevation) attrs.push(`app:cardElevation="${p.elevation}dp"`);
      if (p.cardCornerRadius) attrs.push(`app:cardCornerRadius="${p.cardCornerRadius}dp"`);
      if (p.backgroundColor) attrs.push(`app:cardBackgroundColor="${escapeXml(p.backgroundColor)}"`);

      // MaterialCardView wrapper containing vertical LinearLayout for children
      const hasChildren = comp.children && comp.children.length > 0;
      if (!hasChildren) {
        return `${indent}<com.google.android.material.card.MaterialCardView\n${attrs.map((a) => `${childIndent}${a}`).join('\n')} />`;
      }

      const innerContent = comp.children!
        .map((child) => renderComponentToXml(child, indentDepth + 2, false, stringsMap, colorsMap))
        .join('\n\n');

      return `${indent}<com.google.android.material.card.MaterialCardView\n${attrs.map((a) => `${childIndent}${a}`).join('\n')}>\n\n${indent}    <LinearLayout\n${indent}        android:layout_width="match_parent"\n${indent}        android:layout_height="wrap_content"\n${indent}        android:orientation="vertical">\n\n${innerContent}\n\n${indent}    </LinearLayout>\n\n${indent}</com.google.android.material.card.MaterialCardView>`;
    }

    case 'scrollView': {
      attrs.push('android:fillViewport="true"');
      const hasChildren = comp.children && comp.children.length > 0;
      if (!hasChildren) {
        return `${indent}<ScrollView\n${attrs.map((a) => `${childIndent}${a}`).join('\n')} />`;
      }

      // ScrollView in Android can only take 1 direct child; wrap in LinearLayout if multiple
      const renderedInner = comp.children!
        .map((child) => renderComponentToXml(child, indentDepth + 2, false, stringsMap, colorsMap))
        .join('\n\n');

      return `${indent}<ScrollView\n${attrs.map((a) => `${childIndent}${a}`).join('\n')}>\n\n${indent}    <LinearLayout\n${indent}        android:layout_width="match_parent"\n${indent}        android:layout_height="wrap_content"\n${indent}        android:orientation="vertical">\n\n${renderedInner}\n\n${indent}    </LinearLayout>\n\n${indent}</ScrollView>`;
    }

    case 'container': {
      const hasChildren = comp.children && comp.children.length > 0;
      if (!hasChildren) {
        return `${indent}<FrameLayout\n${attrs.map((a) => `${childIndent}${a}`).join('\n')} />`;
      }

      const renderedChildren = comp.children!
        .map((child) => renderComponentToXml(child, indentDepth + 1, false, stringsMap, colorsMap))
        .join('\n\n');

      return `${indent}<FrameLayout\n${attrs.map((a) => `${childIndent}${a}`).join('\n')}>\n\n${renderedChildren}\n\n${indent}</FrameLayout>`;
    }

    case 'heading':
    case 'text':
    case 'label': {
      const textVal = p.text || (comp.type === 'heading' ? 'Heading' : 'Sample Text');
      attrs.push(`android:text="${escapeXml(textVal)}"`);

      if (p.textSize) attrs.push(`android:textSize="${p.textSize}sp"`);
      if (p.textColor) attrs.push(`android:textColor="${escapeXml(p.textColor)}"`);
      if (p.textStyle && p.textStyle !== 'normal') attrs.push(`android:textStyle="${p.textStyle}"`);
      if (p.textAlignment) {
        const gravityMap: Record<string, string> = { start: 'start', center: 'center', end: 'end' };
        attrs.push(`android:gravity="${gravityMap[p.textAlignment] || 'start'}"`);
      }
      if (p.maxLines) attrs.push(`android:maxLines="${p.maxLines}"`);

      return `${indent}<TextView\n${attrs.map((a) => `${childIndent}${a}`).join('\n')} />`;
    }

    case 'button': {
      const label = p.buttonLabel || 'Button';
      attrs.push(`android:text="${escapeXml(label)}"`);
      if (p.buttonTextColor) attrs.push(`android:textColor="${escapeXml(p.buttonTextColor)}"`);
      if (p.buttonBackgroundColor) attrs.push(`app:backgroundTint="${escapeXml(p.buttonBackgroundColor)}"`);
      if (p.cornerRadius) attrs.push(`app:cornerRadius="${p.cornerRadius}dp"`);
      if (p.textSize) attrs.push(`android:textSize="${p.textSize}sp"`);

      return `${indent}<com.google.android.material.button.MaterialButton\n${attrs.map((a) => `${childIndent}${a}`).join('\n')} />`;
    }

    case 'textField':
    case 'passwordField': {
      const hint = p.hint || (comp.type === 'passwordField' ? 'Password' : 'Enter text');
      const inputType = comp.type === 'passwordField' ? 'textPassword' : p.inputType || 'text';

      // We render a clean Material Design TextInputLayout + TextInputEditText
      const inputAttrs: string[] = [
        `android:id="@+id/${escapeXml(comp.id)}_input"`,
        'android:layout_width="match_parent"',
        'android:layout_height="wrap_content"',
        `android:inputType="${inputType}"`,
      ];

      attrs.push(`android:hint="${escapeXml(hint)}"`);
      if (comp.type === 'passwordField') {
        attrs.push('app:passwordToggleEnabled="true"');
      }

      return `${indent}<com.google.android.material.textfield.TextInputLayout\n${attrs.map((a) => `${childIndent}${a}`).join('\n')}>\n\n${indent}    <com.google.android.material.textfield.TextInputEditText\n${inputAttrs.map((a) => `${indent}        ${a}`).join('\n')} />\n\n${indent}</com.google.android.material.textfield.TextInputLayout>`;
    }

    case 'checkbox': {
      const label = p.label || 'Checkbox option';
      attrs.push(`android:text="${escapeXml(label)}"`);
      if (p.isChecked) attrs.push('android:checked="true"');
      if (p.tintColor) attrs.push(`app:buttonTint="${escapeXml(p.tintColor)}"`);

      return `${indent}<CheckBox\n${attrs.map((a) => `${childIndent}${a}`).join('\n')} />`;
    }

    case 'switch': {
      const label = p.label || 'Switch option';
      attrs.push(`android:text="${escapeXml(label)}"`);
      if (p.isChecked) attrs.push('android:checked="true"');
      if (p.tintColor) attrs.push(`app:thumbTint="${escapeXml(p.tintColor)}"`);

      return `${indent}<com.google.android.material.materialswitch.MaterialSwitch\n${attrs.map((a) => `${childIndent}${a}`).join('\n')} />`;
    }

    case 'radioButton': {
      const label = p.label || 'Radio choice';
      attrs.push(`android:text="${escapeXml(label)}"`);
      if (p.isChecked) attrs.push('android:checked="true"');
      if (p.tintColor) attrs.push(`app:buttonTint="${escapeXml(p.tintColor)}"`);

      return `${indent}<RadioButton\n${attrs.map((a) => `${childIndent}${a}`).join('\n')} />`;
    }

    case 'image': {
      attrs.push(`android:contentDescription="${escapeXml(p.contentDescription || 'App Image')}"`);
      if (p.scaleType) attrs.push(`android:scaleType="${p.scaleType}"`);
      attrs.push('tools:srcCompat="@tools:sample/avatars"');

      return `${indent}<ImageView\n${attrs.map((a) => `${childIndent}${a}`).join('\n')} />`;
    }

    case 'imageButton': {
      attrs.push(`android:contentDescription="${escapeXml(p.contentDescription || 'Action Button')}"`);
      if (p.buttonBackgroundColor) attrs.push(`android:backgroundTint="${escapeXml(p.buttonBackgroundColor)}"`);
      attrs.push('tools:srcCompat="@android:drawable/ic_menu_edit"');

      return `${indent}<ImageButton\n${attrs.map((a) => `${childIndent}${a}`).join('\n')} />`;
    }

    case 'divider': {
      return `${indent}<View\n${attrs.map((a) => `${childIndent}${a}`).join('\n')} />`;
    }

    case 'spacer': {
      return `${indent}<Space\n${attrs.map((a) => `${childIndent}${a}`).join('\n')} />`;
    }

    case 'progressBar': {
      if (p.progressStyle === 'horizontal') {
        attrs.push('style="?android:attr/progressBarStyleHorizontal"');
        attrs.push(`android:max="${p.maxProgress || 100}"`);
        attrs.push(`android:progress="${p.progress || 50}"`);
      } else {
        attrs.push('style="?android:attr/progressBarStyle"');
      }
      if (p.isIndeterminate) {
        attrs.push('android:indeterminate="true"');
      }

      return `${indent}<ProgressBar\n${attrs.map((a) => `${childIndent}${a}`).join('\n')} />`;
    }

    default: {
      return `${indent}<!-- Unrecognized Component: ${escapeXml(comp.type)} -->\n${indent}<View\n${attrs.map((a) => `${childIndent}${a}`).join('\n')} />`;
    }
  }
}
